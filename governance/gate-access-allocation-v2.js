"use strict";
/** Gate-access allocation v3: fail closed; no PINs in outputs or logs. */
const POLICY = Object.freeze({ masterSlot:100, employee:[200,299], visitor:[300,1000], visitorMaxUses:10 });
const inRange=(s,[a,b])=>Number.isInteger(s)&&s>=a&&s<=b;
function classify(slot) {
  if(slot===100)return "MASTER";
  if(inRange(slot,POLICY.employee))return "EMPLOYEE";
  if(inRange(slot,POLICY.visitor))return "VISITOR";
  return "INVALID";
}
/**
 * Read-only reconciliation. Input inventory must be authoritative and complete.
 * approved fields require explicit evidence (not truthiness of provisional CRM notes).
 * pinFingerprint must be a keyed, non-reversible fingerprint generated by secure vault;
 * never pass or store plaintext PINs in CRM or this function.
 */
function reconcile({records, controllerSlots, inventoryComplete=false}) {
  if(!Array.isArray(records)||!Array.isArray(controllerSlots))throw Error("Invalid inventory");
  const issues=[], allocations=[], seenSlots=new Set(), seenPins=new Set();
  for(const r of records) {
    const reasons=[];
    if(classify(r.slot)!==r.userType)reasons.push("SLOT_TYPE_MISMATCH");
    if(seenSlots.has(r.slot))reasons.push("DUPLICATE_SLOT");
    seenSlots.add(r.slot);
    if(!r.pinFingerprint)reasons.push("PIN_NOT_VERIFIED");
    else {
      if(seenPins.has(r.pinFingerprint))reasons.push("DUPLICATE_PIN");
      seenPins.add(r.pinFingerprint);
    }
    if(r.userType==="EMPLOYEE") {
      if(r.identityVerified!==true)reasons.push("IDENTITY_NOT_VERIFIED");
      if(r.onboardingApproved!==true)reasons.push("ONBOARDING_NOT_APPROVED");
      if(r.employeeConfirmed!==true)reasons.push("EMPLOYMENT_NOT_CONFIRMED");
      if(r.slotApproved!==true)reasons.push("SLOT_NOT_APPROVED");
      if(r.pinApproved!==true)reasons.push("PIN_NOT_APPROVED");
    }
    if(!inventoryComplete)reasons.push("CONTROLLER_INVENTORY_INCOMPLETE");
    const matches=controllerSlots.filter(c=>c.slot===r.slot&&c.contactId===r.contactId&&c.pinFingerprint===r.pinFingerprint&&c.programmed===true);
    if(matches.length!==1)reasons.push("CONTROLLER_MAPPING_UNVERIFIED");
    issues.push(...reasons.map(reason=>({contactId:r.contactId,reason})));
    allocations.push({contactId:r.contactId,slot:r.slot,userType:r.userType,
      status:reasons.length?"PENDING_APPROVAL":"VERIFIED_FOR_SEPARATE_ACTIVATION",
      accessActive:false});
  }
  return {policy:POLICY,allocations,issues,safeToActivate:false};
}
function onDocumentUploaded(event) {
  if(event?.event!=="DOCUMENT_UPLOADED"||!["SA_ID","DRIVERS_LICENCE"].includes(event.documentType))
    throw Error("Unsupported enrolment trigger");
  return {contactId:event.contactId,status:"PENDING_VERIFICATION",accessActive:false};
}
module.exports={POLICY,classify,reconcile,onDocumentUploaded};
